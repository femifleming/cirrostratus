#!/usr/bin/env python3
"""Generates monsoon/dsp/tables.cc (lookup tables stored in flash)."""
import math, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = []
out.append('// Generated by tools/gen_tables.py - do not edit.\n')
out.append('#include "monsoon/dsp/core.h"\n\nnamespace monsoon {\n')
vals = [math.sin(2 * math.pi * i / 1024) for i in range(1025)]
out.append('const float kSineTable[1025] = {')
for i in range(0, 1025, 6):
    out.append('  ' + ', '.join('%.9ef' % v for v in vals[i:i + 6]) + ',')
out.append('};\n\n}  // namespace monsoon\n')
open(os.path.join(root, 'monsoon/dsp/tables.cc'), 'w').write('\n'.join(out))
