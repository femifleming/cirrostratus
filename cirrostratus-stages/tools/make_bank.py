#!/usr/bin/env python3
"""Builds the oscillator wave bank: stages/dobbel_bank.cc.

Sixteen waveforms (the same shapes as fletchfoorth 1.1), each stored as a
set of band-limited tables, one per octave ("mip levels"): level L holds
harmonics up to 128 >> L. The oscillator picks the two levels around its
pitch and crossfades them, so nothing it plays folds back below Nyquist.

Tables are int16 in flash (no RAM), each with a guard point before it and
two after (t[-1], t[N], t[N + 1]). Every level holds at least 8 points per
harmonic, 16 from 32 harmonics down (and at least 256 points, 128 for the
four top octaves), read with
linear interpolation: its images fall 36 dB or more below the harmonic that
makes them. (1.2 also had a 256-harmonic level at 4 points per harmonic: its
images were the aliases left at low notes. 128 harmonics reach 8.4 kHz at
C2, 4.2 kHz at C1.)
Levels that would hold exactly the same harmonics share one table.

  python3 tools/make_bank.py
"""

import os
import numpy as np

LEVELS = 8            # harmonics 128, 64, ..., 1
TOP = 128
M = 1 << 16           # analysis resolution
FLOOR = 1e-4          # -80 dB: harmonics below this (re the loudest) are dropped
NAMES = ["sine", "triangle", "saw", "square", "pulse 25 %", "pulse 10 %",
         "half sine", "full-wave sine", "pinched sine", "4 steps", "8 steps",
         "formant", "sync saw", "frozen noise", "sine + octave", "organ"]


def smooth_random():
    # stmlib::Random seeded with 0x5d5d5d5d, 16 floats (Engine::BuildBank 1.1)
    state = 0x5D5D5D5D
    out = []
    for _ in range(16):
        state = (state * 1664525 + 1013904223) & 0xFFFFFFFF
        out.append(np.float32(state / 4294967296.0) * 2 - 1)
    out.append(out[0])
    return np.array(out, dtype=np.float64)


def wave(t, p):
    s = np.sin(2 * np.pi * p)
    w = lambda x: x - np.floor(x)
    if t == 0: return s
    if t == 1: return -(1 - 4 * np.abs(p - 0.5))
    if t == 2: return 2 * p - 1
    if t == 3: return np.where(p < 0.5, 1.0, -1.0)
    if t == 4: return np.where(p < 0.25, 1.0, -1.0)
    if t == 5: return np.where(p < 0.1, 1.0, -1.0)
    if t == 6: return np.maximum(s, 0)
    if t == 7: return np.abs(s)
    if t == 8: return s ** 3
    if t == 9: return np.floor(p * 4) / 1.5 - 1
    if t == 10: return np.floor(p * 8) / 3.5 - 1
    if t == 11: return np.sin(2 * np.pi * w(p * 5)) * (0.5 - 0.5 * np.cos(2 * np.pi * p))
    if t == 12: return w(p * 2.7) * 2 - 1
    if t == 13:
        r = smooth_random()
        x = p * 16
        k = np.floor(x).astype(int)
        f = x - k
        e = f * f * (3 - 2 * f)
        return r[k] + (r[k + 1] - r[k]) * e
    if t == 14: return s + 0.5 * np.sin(2 * np.pi * w(p * 2))
    if t == 15:
        return (s + 0.6 * np.sin(2 * np.pi * w(p * 2)) + 0.4 * np.sin(2 * np.pi * w(p * 4))
                + 0.25 * np.sin(2 * np.pi * w(p * 3)))


def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    p = np.arange(M) / M
    data = []
    offsets, bits, gains, tops = [], [], [], []
    for t in range(16):
        c = np.fft.rfft(wave(t, p)) / M
        c[0] = 0.0
        mag = np.abs(c)
        top = int(np.nonzero(mag > FLOOR * mag.max())[0].max())
        tops.append(top)
        cap = 1
        while cap < top: cap *= 2
        tables = {}
        for level in range(LEVELS):
            h = min(TOP >> level, cap, TOP)
            n = max(16 * h if h <= 32 else 8 * h, 256 if h >= 8 else 128)
            if (h, n) not in tables:
                cc = np.zeros(n // 2 + 1, dtype=complex)
                cc[1:h + 1] = c[1:h + 1]
                tables[(h, n)] = np.fft.irfft(cc * n, n)
        peak = max(np.abs(v).max() for v in tables.values())
        scale = 32000.0 / peak
        gains.append(1.0 / scale)
        placed = {}
        row_o, row_b = [], []
        for level in range(LEVELS):
            h = min(TOP >> level, cap, TOP)
            n = max(16 * h if h <= 32 else 8 * h, 256 if h >= 8 else 128)
            if (h, n) not in placed:
                # one guard point before, two after: the cubic read needs
                # no wrapping
                v = [int(round(x)) for x in tables[(h, n)] * scale]
                data.append(v[-1])
                placed[(h, n)] = len(data)
                data.extend(v + v[:2])
            row_o.append(placed[(h, n)])
            row_b.append(n.bit_length() - 1)
        offsets.append(row_o)
        bits.append(row_b)
    assert len(data) < 65536 and max(abs(v) for v in data) <= 32767

    out = []
    out.append("// Generated by tools/make_bank.py: do not edit.")
    out.append("// %d band-limited tables, %d bytes of flash." % (
        sum(len(set(r)) for r in offsets), len(data) * 2))
    out.append("")
    out.append('#include "stages/dobbel.h"')
    out.append("")
    out.append("namespace stages {")
    out.append("namespace dobbel {")
    out.append("")
    out.append("const int16_t kBankData[%d] = {" % len(data))
    for i in range(0, len(data), 12):
        out.append("  " + ", ".join("%d" % v for v in data[i:i + 12]) + ",")
    out.append("};")
    out.append("")
    out.append("const uint16_t kBankOffset[kBankTables][kBankLevels] = {")
    for t in range(16):
        out.append("  { %s },  // %s" % (", ".join("%d" % v for v in offsets[t]), NAMES[t]))
    out.append("};")
    out.append("")
    out.append("const uint8_t kBankBits[kBankTables][kBankLevels] = {")
    for t in range(16):
        out.append("  { %s }," % ", ".join("%d" % v for v in bits[t]))
    out.append("};")
    out.append("")
    out.append("// table units -> the waveform's own units (a saw is -1 to +1)")
    out.append("const float kBankGain[kBankTables] = {")
    for t in range(16):
        out.append("  %.9ef,  // %s, harmonics to %d" % (gains[t], NAMES[t], tops[t]))
    out.append("};")
    out.append("")
    out.append("}  // namespace dobbel")
    out.append("}  // namespace stages")
    path = os.path.join(root, "stages", "dobbel_bank.cc")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("%s: %d bytes" % (os.path.relpath(path), len(data) * 2))


if __name__ == "__main__":
    main()
